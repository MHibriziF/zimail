#!/usr/bin/env node
/**
 * Inlines `migrations/*.sql` into a plain TypeScript module.
 *
 * The Worker applies its own migrations, so the SQL has to reach the bundle.
 * `import.meta.glob` cannot do it: `src/worker.ts` is bundled by wrangler with
 * esbuild rather than by Vite, so the call survives untransformed and throws
 * `(intermediate value).glob is not a function` when Cloudflare validates the
 * upload. A generated module is understood by both.
 *
 * `migrations/archive/` holds what a squash replaced (#175). Those ship too,
 * marked archived, for databases that only got part of the way through them.
 *
 * The output is committed, so `vite dev` and a fresh clone need no build step;
 * `migrations.generated.test.ts` fails if it drifts from the .sql files.
 */
import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';

const root = path.resolve(import.meta.dirname, '..');
const dir = path.join(root, 'migrations');
const archiveDir = path.join(dir, 'archive');
const out = path.join(root, 'src/lib/server/migrations/migrations.generated.ts');
const REPLACES_PREFIX = '-- replaces:';

function sqlFiles(folder) {
	return existsSync(folder) ? readdirSync(folder).filter((name) => name.endsWith('.sql')).sort() : [];
}

function replacedBy(sql) {
	const line = sql.split('\n').find((entry) => entry.startsWith(REPLACES_PREFIX));
	return line ? line.slice(REPLACES_PREFIX.length).trim().split(/\s+/).filter(Boolean) : [];
}

function entry(folder, name, archived) {
	// Normalized regardless of the checkout's line endings (e.g. Windows + core.autocrlf) —
	// otherwise a CRLF working tree bakes CRLF into this file's string literals, which then
	// mismatches migrations.generated.test.ts on a Linux CI runner that checks out plain LF.
	const sql = readFileSync(path.join(folder, name), 'utf8').replaceAll('\r\n', '\n');
	const replaces = replacedBy(sql);
	const fields = [
		`name: ${JSON.stringify(name)}`,
		...(replaces.length > 0 ? [`replaces: ${JSON.stringify(replaces)}`] : []),
		...(archived ? ['archived: true'] : []),
		`sql: ${JSON.stringify(sql)}`
	];
	const body = fields.map((field) => '\t\t' + field).join(',\n');
	return `\t{\n${body}\n\t}`;
}

const current = sqlFiles(dir);
if (current.length === 0) {
	throw new Error('No migrations found to generate from.');
}
const archived = sqlFiles(archiveDir);

const entries = [
	...current.map((name) => entry(dir, name, false)),
	...archived.map((name) => entry(archiveDir, name, true))
].join(',\n');

const contents = `// Generated by scripts/generate-migrations.mjs — do not edit.
// Run \`bun scripts/generate-migrations.mjs\` after adding a migration.

import type { PlannedMigration } from './plan';

/** Every file in \`migrations/\`, then what squashes replaced, from \`migrations/archive/\`. */
export const MIGRATIONS: PlannedMigration[] = [
${entries}
];
`;

writeFileSync(out, contents, 'utf8');
console.log(
	`generate-migrations: ${current.length} current + ${archived.length} archived migrations -> ${path.relative(root, out)}`
);
